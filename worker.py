@handler("bootstrap_taxonomy")
def _bootstrap_taxonomy(payload: dict) -> None:
    """Customer asked to build their product areas from their docs URL."""
    import feedback_platform as fp

    workspace_id = payload["workspace_id"]
    try:
        nodes = fp.bootstrap_taxonomy_from_url(payload["url"], workspace_id)
    except fp.TaxonomyError as exc:
        raise jobs.PermanentJobError(str(exc)) from exc
    fp.reclassify_workspace(workspace_id)
    fp.rebuild_buckets(workspace_id)
    _log_activity(
        workspace_id,
        title="Product areas updated",
        description=f"{nodes} areas from {payload['url'][:120]}; reviews re-sorted",
        icon="category",
    )


