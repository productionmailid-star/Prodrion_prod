    fp.ensure_taxonomy(workspace_id)
    fp.rebuild_buckets(workspace_id)
    jobs.enqueue(
        "rebuild_buckets_tick",
        {"workspace_id": workspace_id},
        delay_seconds=_BUCKET_REBUILD_INTERVAL,
    )


